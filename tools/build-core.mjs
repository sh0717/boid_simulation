import { spawnSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CORE_SOURCES, coreSourceHash } from './core-sources.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const sdk = process.env.EMSDK || path.join(root, 'artifacts/emsdk');
const compiler = path.join(sdk, 'upstream/emscripten/em++.py');
const bundledPython = path.join(sdk, 'python/3.13.3_64bit/python.exe');
const python = process.env.EMSDK_PYTHON || (existsSync(bundledPython) ? bundledPython : 'python');
if (!existsSync(compiler) || !existsSync(path.join(sdk, '.emscripten'))) {
  throw new Error(
    'Emscripten 4.0.23 is required. See docs/cpp-core.md or set EMSDK to an activated SDK.',
  );
}
const env = {
  ...process.env,
  EM_CONFIG: path.join(sdk, '.emscripten'),
  EM_CACHE: path.join(sdk, 'upstream/emscripten/cache'),
};
const run = (args) => {
  const result = spawnSync(python, [compiler, ...args], { cwd: root, env, encoding: 'utf8' });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(result.stdout + result.stderr);
  return result.stdout;
};
const version = run(['--version']);
if (!/^emcc.*4\.0\.23\b/m.test(version))
  throw new Error(`Expected Emscripten 4.0.23; got ${version.split('\n')[0]}`);
await mkdir(path.join(root, 'build/wasm'), { recursive: true });
run([
  ...CORE_SOURCES,
  '-Inative/bindings/include',
  '-Inative/src',
  '-Inative/bindings',
  '-std=c++20',
  '-O3',
  '-Wall',
  '-Wextra',
  '-Werror',
  '-ffp-contract=off',
  '-fno-exceptions',
  '-fno-rtti',
  '-DNDEBUG',
  '--no-entry',
  '-sSTANDALONE_WASM=1',
  '-sFILESYSTEM=0',
  '-sMALLOC=emmalloc',
  '-sINITIAL_MEMORY=2097152',
  '-sSTACK_SIZE=65536',
  '-sALLOW_MEMORY_GROWTH=0',
  '-o',
  'build/wasm/boids.wasm',
]);
const binary = await readFile(path.join(root, 'build/wasm/boids.wasm'));
const module = new WebAssembly.Module(binary);
const imports = WebAssembly.Module.imports(module);
if (imports.length) throw new Error(`Unexpected core imports: ${JSON.stringify(imports)}`);
const metadata = {
  compiler: 'Emscripten 4.0.23',
  standard: 'C++20',
  abi: 1,
  bytes: binary.length,
  sourceSha256: await coreSourceHash(),
  wasmSha256: createHash('sha256').update(binary).digest('hex'),
};
await mkdir(path.join(root, 'src/simulation/generated'), { recursive: true });
await writeFile(
  path.join(root, 'src/simulation/generated/core-binary.js'),
  `// Generated by npm run build:core. Do not edit.\nexport const CORE_METADATA = ${JSON.stringify(metadata)};\nexport const CORE_BASE64 = '${binary.toString('base64')}';\n`,
);
const notices = await Promise.all(
  ['LICENSE', 'system/lib/libc/musl/COPYRIGHT', 'system/lib/libcxx/LICENSE.TXT'].map(
    async (file) =>
      `Emscripten 4.0.23: ${file}\n\n${await readFile(path.join(sdk, 'upstream/emscripten', file), 'utf8')}`,
  ),
);
notices.push(
  'Emscripten emmalloc\nCopyright 2018 The Emscripten Authors. All rights reserved.\nAvailable under the MIT and University of Illinois/NCSA licenses reproduced above.',
);
await writeFile(
  path.join(root, 'src/simulation/generated/core-licenses.txt'),
  notices.join('\n\n'),
);
console.log(`Built C++20 core: ${binary.length} bytes, no imports, fixed 2 MiB memory.`);
