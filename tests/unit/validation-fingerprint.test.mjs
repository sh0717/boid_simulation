import assert from 'node:assert/strict';
import test from 'node:test';
import { mkdtemp, mkdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { runtimeFingerprint, sourceFingerprint } from '../../tools/validation-fingerprint.mjs';

test('source identity detects code and shared settings while ignoring documentation and local paths', async () => {
  const root = await mkdtemp(path.join(tmpdir(), 'boids-fingerprint-'));
  try {
    await mkdir(path.join(root, 'src/simulation/generated'), { recursive: true });
    await mkdir(path.join(root, '.vscode'));
    await mkdir(path.join(root, 'docs'));
    const source = path.join(root, 'src/app.js');
    await writeFile(source, 'const value = 1;\n');
    const original = (await sourceFingerprint(root)).sha256;
    await writeFile(source, 'const value = 1;\r\n');
    await writeFile(path.join(root, 'README.md'), 'Documentation\n');
    await writeFile(path.join(root, 'docs/notes.md'), 'Local working notes\n');
    await writeFile(path.join(root, 'src/simulation/generated/core-binary.js'), 'Generated output');
    await writeFile(path.join(root, '.vscode/c_cpp_properties.json'), 'Local compiler path');
    await writeFile(path.join(root, 'CMakeUserPresets.json'), 'Local build path');
    assert.equal((await sourceFingerprint(root)).sha256, original);
    await writeFile(path.join(root, '.vscode/settings.json'), '{}');
    assert.notEqual((await sourceFingerprint(root)).sha256, original);
    const beforeSourceEdit = (await sourceFingerprint(root)).sha256;
    await writeFile(source, 'const value = 2;\n');
    assert.notEqual((await sourceFingerprint(root)).sha256, beforeSourceEdit);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test('runtime identity detects changed generated bytes and newly added deployed files', async () => {
  const root = await mkdtemp(path.join(tmpdir(), 'boids-runtime-'));
  try {
    await mkdir(path.join(root, 'wasm'));
    const binary = path.join(root, 'wasm/boids-core.wasm');
    await writeFile(binary, Buffer.from([0, 97, 115, 109]));
    const original = (await runtimeFingerprint(root)).sha256;
    await writeFile(binary, Buffer.from([0, 97, 115, 110]));
    assert.notEqual((await runtimeFingerprint(root)).sha256, original);
    const beforeNewFile = (await runtimeFingerprint(root)).sha256;
    await writeFile(path.join(root, 'yoosh.html'), 'Generated entry');
    assert.notEqual((await runtimeFingerprint(root)).sha256, beforeNewFile);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});
